function buildReverseQuestions(questionBank) {
  const chapterFor = lo => questionBank.find(q => q.lo === lo)?.chapter || `${String(lo)[0]}장`;
  return REVERSE_CONCEPTS.map((item, index) => {
    const [lo, level, section, term, clue, note] = item;
    const sameSection = REVERSE_CONCEPTS.filter((candidate, i) => i !== index && candidate[2] === section);
    const sameChapter = REVERSE_CONCEPTS.filter((candidate, i) => i !== index && candidate[0][0] === lo[0] && !sameSection.includes(candidate));
    const others = REVERSE_CONCEPTS.filter((candidate, i) => i !== index && candidate[0][0] !== lo[0]);
    const candidates = [...sameSection, ...sameChapter, ...others];
    const distractors = [];
    for (let step = 0; distractors.length < 3 && step < candidates.length * 2; step++) {
      const candidate = candidates[(index * 5 + step * 7) % candidates.length];
      if (candidate[3] !== term && !distractors.includes(candidate[3])) distractors.push(candidate[3]);
    }
    const answerPosition = (index * 3 + Number(lo[0])) % 4;
    const options = [...distractors];
    options.splice(answerPosition, 0, term);
    return {
      id: `REV-${lo}`,
      set: 'reverse-concepts',
      chapter: chapterFor(lo),
      lo,
      level,
      text: `다음 설명에 해당하는 개념은?\n\n${clue}`,
      options,
      answer: [answerPosition],
      explanation: `정답은 ‘${term}’이다. ${note}`,
      reverseTerm: term
    };
  });
}
